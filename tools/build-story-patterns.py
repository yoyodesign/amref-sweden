#!/usr/bin/env python3
"""
Bundle the homepage line SVGs into js/story-patterns.js.

Run this after editing or adding any of the line SVGs in assets/svgs/:

    python3 tools/build-story-patterns.py

Why: browsers block a page opened straight from Finder (file://) from
loading other files with fetch(), so the SVGs are bundled into a script
instead. This also means one request instead of twenty.

What gets bundled:
  - Logo lines:  home-lines.svg (desktop), mobile-home-lines.svg (mobile)
  - Story title frame: title-left.svg, title-step.svg, title-right.svg, title-tail.svg
  - Card patterns: any name X with all four files present:
        X.svg, X-under.svg, mobile-X.svg, mobile-X-under.svg
    e.g. purple, yellow, blue, green, terracotta.

A new pattern also needs a photoX entry in js/story-lines.js and a colour
rule (.story-card[data-line='X']) in css/styles.css.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SVG_DIR = os.path.join(ROOT, 'assets', 'svgs')
OUT = os.path.join(ROOT, 'js', 'story-patterns.js')

LOGOS = ['home-lines.svg', 'mobile-home-lines.svg']

# Story page title frame pieces (js/title-frame.js stretches the lines between them)
TITLE_PIECES = ['title-left.svg', 'title-step.svg', 'title-right.svg', 'title-tail.svg']


def read(name):
    with open(os.path.join(SVG_DIR, name), encoding='utf-8') as f:
        svg = f.read()
    # Collapse whitespace between tags so the bundle stays compact
    return re.sub(r'>\s+<', '><', svg).strip()


def main():
    files = set(os.listdir(SVG_DIR))
    patterns = sorted(
        f[: -len('-under.svg')]
        for f in files
        if f.endswith('-under.svg')
        and not f.startswith('mobile-')
        and {f[: -len('-under.svg')] + '.svg',
             'mobile-' + f[: -len('-under.svg')] + '.svg',
             'mobile-' + f}.issubset(files)
    )

    missing = [l for l in LOGOS + TITLE_PIECES if l not in files]
    if missing:
        sys.exit('Missing logo SVG(s): ' + ', '.join(missing))

    bundle = {name: read(name) for name in LOGOS + TITLE_PIECES}
    for p in patterns:
        for name in (p + '.svg', p + '-under.svg', 'mobile-' + p + '.svg', 'mobile-' + p + '-under.svg'):
            bundle[name] = read(name)

    js = (
        '/* GENERATED by tools/build-story-patterns.py from assets/svgs/ — do not edit.\n'
        '   Re-run:  python3 tools/build-story-patterns.py\n'
        '   Patterns: ' + ', '.join(patterns) + ' */\n'
        'window.STORY_PATTERNS = ' + json.dumps(bundle, indent=2) + ';\n'
    )
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(js)

    print('Wrote js/story-patterns.js')
    print('  logos:    ' + ', '.join(LOGOS))
    print('  title:    ' + ', '.join(TITLE_PIECES))
    print('  patterns: ' + ', '.join(patterns))


if __name__ == '__main__':
    main()
